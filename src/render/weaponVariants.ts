import { pixelPainter } from "./pixels";
/** Cosmetic silhouettes only. Equipped weapon type and combat parameters stay unchanged. */
export function drawWeaponVariant(
  ctx: CanvasRenderingContext2D,
  key: string,
  style: number,
) {
  const { rect: r, poly: p } = pixelPainter(ctx),
    ink = "#242638",
    metal = "#b2c1c9",
    shine = "#ecedda",
    gold = "#d7b66d",
    wood = style === 1 ? "#a56b51" : "#6c5365";
  if (key.includes("bow")) {
    if (style === 1) {
      p(
        [
          [50, 24],
          [56, 27],
          [54, 35],
          [59, 43],
          [57, 52],
          [52, 63],
          [49, 62],
          [53, 51],
          [55, 43],
          [51, 35],
          [53, 28],
        ],
        ink,
      );
      p(
        [
          [51, 26],
          [54, 28],
          [52, 35],
          [57, 43],
          [55, 52],
          [50, 61],
          [54, 46],
          [53, 39],
          [50, 34],
        ],
        wood,
      );
    } else {
      p(
        [
          [50, 17],
          [55, 26],
          [59, 42],
          [56, 59],
          [50, 69],
          [49, 66],
          [53, 55],
          [55, 42],
          [52, 28],
          [49, 20],
        ],
        ink,
      );
      p(
        [
          [51, 21],
          [54, 29],
          [57, 42],
          [54, 58],
          [50, 65],
          [54, 43],
        ],
        wood,
      );
      r(54, 38, 3, 8, gold);
    }
    r(49, style === 1 ? 26 : 20, 1, style === 1 ? 35 : 46, "#ead9b1");
    r(47, 42, 9, 3, "#76553e");
  } else if (key.includes("staff")) {
    r(50, 22, 4, 48, ink);
    r(51, 23, 2, 45, wood);
    r(51, 31, 1, 34, gold);
    if (style === 1) {
      p(
        [
          [44, 10],
          [49, 15],
          [51, 8],
          [54, 15],
          [59, 10],
          [57, 24],
          [46, 24],
        ],
        ink,
      );
      p(
        [
          [46, 13],
          [50, 19],
          [51, 12],
          [54, 20],
          [57, 13],
          [55, 22],
          [48, 22],
        ],
        gold,
      );
      r(50, 17, 4, 5, "#a58ed0");
      r(51, 17, 2, 2, shine);
    } else {
      p(
        [
          [48, 10],
          [54, 10],
          [59, 15],
          [59, 21],
          [54, 26],
          [48, 26],
          [43, 21],
          [43, 15],
        ],
        ink,
      );
      p(
        [
          [49, 12],
          [53, 12],
          [57, 16],
          [57, 20],
          [53, 24],
          [49, 24],
          [45, 20],
          [45, 16],
        ],
        gold,
      );
      p(
        [
          [50, 14],
          [54, 17],
          [53, 21],
          [49, 22],
          [47, 18],
        ],
        "#8eadd0",
      );
      r(49, 15, 3, 3, shine);
    }
  } else if (key.includes("spear")) {
    r(50, 22, 4, 48, ink);
    r(51, 23, 2, 45, wood);
    if (style === 1) {
      p(
        [
          [52, 3],
          [59, 15],
          [55, 23],
          [48, 23],
          [45, 15],
        ],
        ink,
      );
      p(
        [
          [52, 6],
          [56, 15],
          [53, 21],
          [49, 21],
          [48, 15],
        ],
        metal,
      );
      r(51, 10, 2, 10, shine);
      r(45, 23, 15, 3, gold);
    } else {
      p(
        [
          [52, 3],
          [59, 12],
          [57, 23],
          [52, 27],
          [48, 21],
          [51, 15],
        ],
        ink,
      );
      p(
        [
          [53, 6],
          [57, 13],
          [55, 22],
          [52, 24],
          [50, 21],
          [53, 15],
        ],
        metal,
      );
      r(51, 27, 4, 6, "#a65e62");
    }
  } else if (key.includes("lute")) {
    r(49, 31, 4, 25, ink);
    r(50, 32, 2, 23, wood);
    p(
      style === 1
        ? [
            [46, 47],
            [56, 47],
            [60, 53],
            [59, 62],
            [53, 68],
            [46, 65],
            [41, 58],
            [42, 51],
          ]
        : [
            [47, 46],
            [55, 46],
            [55, 51],
            [59, 56],
            [56, 64],
            [50, 67],
            [43, 62],
            [43, 55],
            [47, 51],
          ],
      ink,
    );
    p(
      style === 1
        ? [
            [47, 49],
            [55, 49],
            [58, 54],
            [57, 61],
            [52, 65],
            [47, 63],
            [43, 57],
            [44, 52],
          ]
        : [
            [49, 48],
            [53, 48],
            [53, 53],
            [57, 57],
            [54, 62],
            [50, 64],
            [45, 60],
            [45, 56],
            [49, 52],
          ],
      wood,
    );
    r(49, 53, 4, 5, ink);
    r(50, 33, 1, 30, gold);
    r(46, 60, 9, 2, gold);
  } else {
    const top = key.includes("dagger") ? 37 : 19;
    if (style === 1) {
      p(
        [
          [51, top],
          [57, top + 8],
          [56, 54],
          [46, 54],
          [46, top + 8],
        ],
        ink,
      );
      p(
        [
          [51, top + 3],
          [55, top + 9],
          [54, 52],
          [48, 52],
          [48, top + 9],
        ],
        metal,
      );
      r(50, top + 7, 2, 46 - top, shine);
    } else {
      p(
        [
          [56, top],
          [59, top + 8],
          [56, 38],
          [52, 54],
          [46, 55],
          [50, 38],
          [52, top + 8],
        ],
        ink,
      );
      p(
        [
          [56, top + 4],
          [57, top + 9],
          [54, 39],
          [50, 52],
          [48, 53],
          [52, 38],
          [54, top + 9],
        ],
        metal,
      );
      r(54, top + 10, 1, Math.max(1, 33 - top), shine);
    }
    r(44, 54, 15, 4, ink);
    r(45, 55, 13, 2, gold);
    r(50, 58, 4, 10, wood);
    r(49, 67, 6, 2, gold);
  }
}
